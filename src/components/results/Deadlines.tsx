"use client";

import { Clock, Download } from "lucide-react";
import { motion } from "motion/react";
import { PROVISION_BY_ID } from "@/lib/provisions";
import type { Analysis, Obligation } from "@/lib/types";
import { Button } from "../ui";
import { PHASES } from "./shared";

interface Row extends Obligation {
  provisionId: string;
}

// A deadline with a number in it ("within 7 days") is time-critical; missing it usually costs a claim.
const isTimed = (o: Obligation) => Boolean(o.deadline && /\d/.test(o.deadline));

export function Deadlines({ analysis, onOpenProvision }: { analysis: Analysis; onOpenProvision: (id: string) => void }) {
  const rows: Row[] = analysis.reviews.flatMap((r) => r.provisions.flatMap((p) => p.obligations.map((o) => ({ ...o, provisionId: p.provision_id }))));
  const timed = rows.filter(isTimed).length;

  function download() {
    const lines = [`# Obligations checklist: ${analysis.deal.packageType}`, ""];
    for (const phase of PHASES) {
      const items = rows.filter((r) => r.phase === phase.id);
      if (!items.length) continue;
      lines.push(`## ${phase.label}`, "");
      items.forEach((r) => lines.push(`- [ ] ${r.action}${r.deadline ? ` — **${r.deadline}**` : ""} _(${PROVISION_BY_ID[r.provisionId]?.label ?? r.provisionId})_`));
      lines.push("");
    }
    lines.push("_Generated by DealGuard MY. Commercial guidance only, not legal advice._");
    const url = URL.createObjectURL(new Blob([lines.join("\n")], { type: "text/markdown" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = "dealguard-obligations.md";
    a.click();
    URL.revokeObjectURL(url);
  }

  return (
    <div>
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <h2 className="text-[20px] font-semibold tracking-tight">
            {rows.length} things this contract makes you do, {timed} on a strict clock
          </h2>
          <p className="mt-1 max-w-2xl text-[14px] text-ink-2">Miss a notice or time bar and you can lose an extension of time or a variation claim, however good your case. Pin this to the site office.</p>
        </div>
        <Button onClick={download}>
          <Download size={15} aria-hidden /> Download checklist
        </Button>
      </div>

      <div className="mt-6 -mx-4 overflow-x-auto px-4 pb-2 sm:mx-0 sm:px-0">
        <ol className="grid min-w-[900px] grid-cols-5 gap-3">
          {PHASES.map((phase, col) => {
            const items = rows.filter((r) => r.phase === phase.id).sort((a, b) => Number(isTimed(b)) - Number(isTimed(a)));
            return (
              <li key={phase.id} className="min-w-0">
                <div className="relative mb-3">
                  <div className="h-1 rounded-full bg-sunken">
                    <motion.div
                      className="h-1 rounded-full bg-brand"
                      initial={{ scaleX: 0 }}
                      animate={{ scaleX: 1 }}
                      transition={{ delay: col * 0.12, duration: 0.4 }}
                      style={{ transformOrigin: "left" }}
                    />
                  </div>
                  <p className="mt-2.5 flex items-baseline justify-between text-[14px] font-semibold">
                    {phase.label} <span className="text-[12px] font-normal tabular text-ink-3">{items.length}</span>
                  </p>
                  <p className="text-[12px] text-ink-3">{phase.hint}</p>
                </div>
                <ul className="space-y-2">
                  {items.map((r, i) => (
                    <motion.li key={i} initial={{ opacity: 0, y: 6 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: col * 0.12 + i * 0.04 }}>
                      <button
                        onClick={() => onOpenProvision(r.provisionId)}
                        className="w-full rounded-lg border border-line bg-surface px-3 py-2.5 text-left hover:border-brand"
                      >
                        <p className="text-[13.5px] leading-snug">{r.action}</p>
                        {r.deadline ? (
                          <p
                            className="mt-1.5 inline-flex items-center gap-1 text-[12px] font-medium"
                            style={{ color: isTimed(r) ? "var(--serious-text)" : "var(--ink-3)" }}
                          >
                            <Clock size={12} aria-hidden /> {r.deadline}
                          </p>
                        ) : null}
                        <p className="mt-1 truncate text-[11.5px] text-ink-3">{PROVISION_BY_ID[r.provisionId]?.label}</p>
                      </button>
                    </motion.li>
                  ))}
                  {!items.length ? <li className="rounded-lg border border-dashed border-line px-3 py-4 text-center text-[12.5px] text-ink-3">Nothing here</li> : null}
                </ul>
              </li>
            );
          })}
        </ol>
      </div>
    </div>
  );
}
